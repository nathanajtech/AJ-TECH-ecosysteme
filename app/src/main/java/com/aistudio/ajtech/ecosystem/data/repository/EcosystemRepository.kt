    fun getEntityById(id: String): EcosystemEntity? {
        return entities.find { it.id == id }
    }

    fun getEntitiesByStatus(status: EntityStatus?): List<EcosystemEntity> {
        if (status == null) return entities
        return entities.filter { it.status == status }
    }

    fun searchEntities(query: String, lang: BookLanguage = BookLanguage.FRENCH): List<EcosystemEntity> {
        if (query.isBlank()) return entities
        val lowercaseQuery = query.lowercase().trim()
        return entities.filter {
            it.name.lowercase().contains(lowercaseQuery) ||
                    it.tagline(lang).lowercase().contains(lowercaseQuery) ||
                    it.origin(lang).lowercase().contains(lowercaseQuery) ||
                    it.mission(lang).lowercase().contains(lowercaseQuery) ||
                    it.problem(lang).lowercase().contains(lowercaseQuery) ||
                    it.solution(lang).lowercase().contains(lowercaseQuery) ||
                    it.techStack(lang).any { tech -> tech.lowercase().contains(lowercaseQuery) }
        }
    }
